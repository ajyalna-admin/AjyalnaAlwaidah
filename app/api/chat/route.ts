export async function POST(req: NextRequest) {
  const apiKey = process.env.ANTHROPIC_API_KEY;

  if (!apiKey) {
    return NextResponse.json(
      { error: "لم يتم إعداد مفتاح الذكاء الاصطناعي بعد." },
      { status: 500 }
    );
  }

  try {
    const { messages } = await req.json();

    const res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": apiKey,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: "claude-sonnet-4-6",
        max_tokens: 1000,
        system: SYSTEM_PROMPT,
        messages,
      }),
    });

    const data = await res.json();

    if (!res.ok) {
      return NextResponse.json(
        { error: data?.error?.message || "صار خطأ بالاتصال." },
        { status: res.status }
      );
    }

    const reply =
      data?.content
        ?.map((b: { type: string; text?: string }) => (b.type === "text" ? b.text : ""))
        .join("\n")
        .trim() || "عذرًا، ما قدرت أجاوب على سؤالك الحين. جرّب مرة ثانية أو راسلنا على Ajyalnaalwaidah@gmail.com";

    return NextResponse.json({ reply });
  } catch {
    return NextResponse.json({ error: "صار خطأ بالاتصال." }, { status: 500 });
  }
}
